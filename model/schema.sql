CREATE TABLE IF NOT EXISTS objetos (
    objeto_id INTEGER PRIMARY KEY AUTOINCREMENT,
    nombre TEXT NOT NULL,
    referencia TEXT NOT NULL DEFAULT '',
    descripcion TEXT NOT NULL DEFAULT '',
    nombre_archivo TEXT NOT NULL,
    fecha_creacion TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ancho_mm REAL NOT NULL,
    alto_mm REAL NOT NULL,
    area_mm2 REAL NOT NULL,
    perimetro_mm REAL NOT NULL,
    ancho_px REAL,
    alto_px REAL,
    angulo REAL,
    centro_x REAL,
    centro_y REAL,
    imagen_original BLOB NOT NULL,
    imagen_color BLOB,
    imagen_bordes BLOB,
    imagen_a4 BLOB NOT NULL,
    imagen_folio BLOB NOT NULL,
    imagen_mascara BLOB NOT NULL,
    imagen_resultado BLOB NOT NULL,
    anotaciones BLOB
);
